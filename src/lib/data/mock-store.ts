// Deterministic telemetry points generator for charts
export function generateInitialTelemetryPoints(pointsCount = 24): MetricPointData[] {
  const points: MetricPointData[] = [];
  const now = Date.now();
  const stepMs = 5 * 60 * 1000; // 5-minute intervals

  for (let i = pointsCount - 1; i >= 0; i--) {
    const timestamp = new Date(now - i * stepMs).toISOString();
    // Simulate anomaly on the last 4 points to mirror the ongoing incident
    const isAnomaly = i <= 3;
    const baseRequests = 2600 + Math.sin(i * 0.4) * 400;
    const baseLatency = isAnomaly ? 320 + (4 - i) * 130 : 138 + Math.cos(i * 0.5) * 15;
    const baseErrorRate = isAnomaly ? 1.8 + (4 - i) * 0.4 : 0.08 + Math.random() * 0.05;
    const baseCpu = isAnomaly ? 78 + (4 - i) * 4 : 38 + Math.sin(i * 0.3) * 8;
    const baseMemory = isAnomaly ? 72 + (4 - i) * 3 : 54 + Math.cos(i * 0.2) * 5;

    points.push({
      timestamp,
      requests: Math.round(baseRequests),
      latency: Math.round(baseLatency),
      errorRate: parseFloat(baseErrorRate.toFixed(2)),
      cpu: parseFloat(baseCpu.toFixed(1)),
      memory: parseFloat(baseMemory.toFixed(1)),
    });
  }

  return points;
}
